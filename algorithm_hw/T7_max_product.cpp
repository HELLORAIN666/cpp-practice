/*
 * T7 乘积最大（循环与条件判断）
 * ------------------------------------------------------------
 * 题目：找 M 个和为 N 的正整数，让它们的乘积最大，升序输出。
 *
 * 直觉：把 N 尽量"平均分"给 M 个数。
 *   6 = 2+2+2 → 8      （最平均，最大）
 *   6 = 1+2+3 → 6
 *   6 = 1+1+4 → 4      （最不平均，最小）
 *
 * 为什么？（这是本题的灵魂，务必理解）
 *   假设有两个数 a 和 b，且 b - a >= 2（差距 ≥ 2）。
 *   现在从 b 身上拿 1 给 a，变成 (a+1) 和 (b-1)：
 *
 *       新乘积 = (a+1)(b-1) = ab - a + b - 1 = ab + (b - a - 1)
 *
 *   因为 b - a >= 2，所以 (b - a - 1) >= 1 > 0，即新乘积 > 原乘积。
 *   结论：只要还有两个数差距 ≥ 2，把它们"拉平"一点，乘积就会变大。
 *        → 一直拉到所有数只差 0 或 1，就是最大乘积。
 *
 *   生活比喻：给你 10 米篱笆围一个矩形菜地，围成正方形（边长接近）面积最大，
 *            拉成又细又长的条，面积就小了。道理完全一样。
 *
 * 做法：
 *   base = N / M          → 每人先分到的"保底"
 *   rest = N % M          → 剩下 rest 个没分完，给最后 rest 个人各多 1
 *   → 前 (M - rest) 个是 base，后 rest 个是 base + 1，天然升序
 * ------------------------------------------------------------
 */
#include <iostream>
using namespace std;

int main()
{
    int N, M;
    cin >> N >> M;

    int base = N / M;
    int rest = N % M;

    for (int i = 1; i <= M; i++)
    {
        // 后 rest 个位置多分 1
        int value = (i <= M - rest) ? base : base + 1;

        if (i > 1)
        {
            cout << " ";
        }
        cout << value;
    }
    cout << endl;

    return 0;
}
