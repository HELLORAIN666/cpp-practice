/*
 * T1 小玉买文具（数据类型）
 * ------------------------------------------------------------
 * 思路：单位统一 + 整数除法
 *   1. 一支笔 1 元 9 角 = 19 角
 *   2. 小玉的钱 a 元 b 角 = a * 10 + b 角
 *   3. 能买几支 = 总角数 / 19（整数除法自动向下取整，正好是"最多能买多少"）
 *
 * 关键点：为什么不直接用 1.9 元去做浮点除法？
 *   因为浮点（double）在计算机里是"近似存储"，0.1 这种数根本存不准。
 *   涉及"钱"的计算，一律换算成最小单位（角/分）用整数算，这是行业惯例。
 * ------------------------------------------------------------
 */
#include <iostream>
using namespace std;

int main()
{
    int a, b;
    cin >> a >> b;

    // 全部换算成"角"，避开浮点误差
    int totalJiao = a * 10 + b;
    const int PRICE = 19; // 一支笔 19 角

    cout << totalJiao / PRICE << endl;

    return 0;
}
