/*
 * T2 数组求和（数组与循环）
 * ------------------------------------------------------------
 * 思路：累加器模式（accumulator）
 *   设一个变量 sum = 0，然后循环 n 次，每次把一个数"倒进"sum 里。
 *   就像拿一个空桶，依次把 n 杯水倒进去，最后桶里就是总量。
 *
 * 两种写法：
 *   A. 边读边加（推荐）—— 不需要真的开数组，省内存
 *   B. 先存进数组再遍历求和 —— 练习数组时使用（下面用这种，方便你体会数组）
 * ------------------------------------------------------------
 */
#include <iostream>
using namespace std;

int main()
{
    int n;
    cin >> n;

    int arr[1000]; // 题目没给 n 上限，开个足够大的静态数组
    long long sum = 0; // 用 long long 防止 n 个数加起来溢出 int

    for (int i = 0; i < n; i++)
    {
        cin >> arr[i];
        sum += arr[i]; // 累加器：每读一个就倒进桶里
    }

    cout << sum << endl;

    return 0;
}
