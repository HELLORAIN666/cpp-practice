/*
 * T5 指针交换变量（指针与函数）
 * ------------------------------------------------------------
 * 思路：为什么普通传值 swap(int x, int y) 不生效？
 *
 *   把变量想象成一间"宿舍"，变量名是门牌号，里面住着值。
 *
 *   传值 swap(a, b)：
 *     函数新开了两间"临时房" x 和 y，把 a、b 房间里的东西复印了一份搬过去。
 *     你在函数里把 x、y 房间互换了 —— 但 a、b 原来的房间纹丝未动。
 *     函数结束，临时房被拆迁，什么都没发生。
 *
 *   传指针 swap(&a, &b)：
 *     这次复印的不是"房间里的东西"，而是"门牌号（地址）"。
 *     函数拿着你家的地址，直接上门把东西换了 —— a、b 真的变了。
 *
 *   一句话：传值 = 给你复印件让你改；传址 = 给你钥匙让你进屋改。
 * ------------------------------------------------------------
 */
#include <iostream>
using namespace std;

// 指针版：x 存的是 a 的地址，*x 就是"顺着地址找到那间房，操作里面的东西"
void swap(int *x, int *y)
{
    int temp = *x; // 取出 x 指向的那个值
    *x = *y;       // 把 y 指向的值写进 x 指向的房间
    *y = temp;     // 再把原来的值写进 y 指向的房间
}

// 对比：这个版本完全无效（副本交换）
void swapByValue(int x, int y)
{
    int temp = x;
    x = y;
    y = temp; // 只换了副本，主函数的 a、b 不受影响
}

int main()
{
    int a, b;
    cin >> a >> b;

    swap(&a, &b); // & 是"取地址"：把 a 的门牌号交给函数

    cout << a << " " << b << endl;

    return 0;
}
